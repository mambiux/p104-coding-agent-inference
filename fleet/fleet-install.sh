#!/usr/bin/env bash
# fleet-install.sh — many P104-100s in one box: one llama-server per card, each pinned to its GPU, ports 8101.., power cap and
# memory offset on every card, systemd template unit, and an nginx least-connections router on one port.
# Run AFTER install.sh (which builds the binaries into ~/bonsai and downloads the model). Idempotent.
set -euo pipefail
ROOT="$HOME/bonsai"; BIN="$ROOT/src/build/bin"
MODEL="${MODEL:-$(ls -1 "$ROOT"/models/*.gguf 2>/dev/null | head -1)}"
CTX="${CTX:-32768}"; SPEC="${SPEC:-ngram-mod}"; POWER_W="${POWER_W:-128}"; MEM_OFFSET="${MEM_OFFSET:-0}"
BASE_PORT="${BASE_PORT:-8101}"; ROUTER_PORT="${ROUTER_PORT:-8080}"; THREADS="${THREADS:-1}"
[ -x "$BIN/llama-server" ] || { echo "no binaries in $BIN; run install.sh first"; exit 1; }
[ -s "$MODEL" ] || { echo "no model file; run install.sh first or set MODEL="; exit 1; }
mapfile -t CARDS < <(nvidia-smi --query-gpu=index,uuid,name,memory.total --format=csv,noheader | grep -i 'P104-100' | awk -F', ' '$4+0 >= 8000 {print $1","$2}')
N=${#CARDS[@]}; [ "$N" -ge 1 ] || { echo "no P104-100 with 8 GB found"; exit 1; }
echo "== $N P104-100 cards with 8 GB; model $(basename "$MODEL"); ctx $CTX; ports $BASE_PORT..$((BASE_PORT+N-1)); router :$ROUTER_PORT"
FREE_KB=$(awk '/MemAvailable/{print $2}' /proc/meminfo); NEED_KB=$(( (6 + N) * 1024 * 1024 ))
[ "$FREE_KB" -ge "$NEED_KB" ] || echo "warning: $((FREE_KB/1024/1024)) GB RAM available; $N servers want roughly $((NEED_KB/1024/1024)) GB (one shared model mapping plus ~1 GB each)"
SPEC_FLAGS="--spec-type $SPEC"; case "$SPEC" in *draft-mtp*) SPEC_FLAGS="$SPEC_FLAGS --spec-draft-n-max 3 --spec-draft-n-min 0 --spec-draft-p-min 0.75";; esac
mkdir -p "$ROOT/fleet"
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
[ "$MEM_OFFSET" != 0 ] && [ -f "$REPO_DIR/scripts/system/p104-memoc-set.py" ] && sudo install -m 755 "$REPO_DIR/scripts/system/p104-memoc-set.py" /usr/local/sbin/p104-memoc-set.py
# one env file per card, one template unit
for entry in "${CARDS[@]}"; do idx=${entry%%,*}; uuid=${entry#*,}; port=$((BASE_PORT+idx))
cat > "$ROOT/fleet/card$idx.env" <<E
GPU_UUID=$uuid
PORT=$port
E
done
cat > "$ROOT/fleet/serve-card.sh" <<E
#!/usr/bin/env bash
# generated by fleet-install.sh — serves one card; env GPU_UUID and PORT come from fleet/cardN.env
export CUDA_VISIBLE_DEVICES=\$GPU_UUID
exec env LD_LIBRARY_PATH=$BIN $BIN/llama-server -m "$MODEL" --host 127.0.0.1 --port \$PORT -ngl 999 --ctx-size $CTX --parallel 1 \\
  -b 512 -ub 256 -fa on --cache-type-k q4_0 --cache-type-v q4_0 --jinja $SPEC_FLAGS --threads $THREADS \\
  --reasoning on --reasoning-effort medium --reasoning-budget 4000 \\
  --reasoning-budget-message "Time to stop thinking and write the final answer now." \\
  --temp 0.7 --top-p 0.95 --top-k 20 --cache-reuse 256
E
chmod +x "$ROOT/fleet/serve-card.sh"
sudo tee /etc/systemd/system/bonsai@.service >/dev/null <<E
[Unit]
Description=Bonsai 2 27B on P104-100 card %i
After=network.target p104-fleet-power.service
[Service]
User=$USER
EnvironmentFile=$ROOT/fleet/card%i.env
ExecStart=$ROOT/fleet/serve-card.sh
Restart=on-failure
RestartSec=10
[Install]
WantedBy=multi-user.target
E
# power cap + memory offset for every card, at boot
cat > "$ROOT/fleet/power.sh" <<E
#!/usr/bin/env bash
for u in \$(nvidia-smi --query-gpu=uuid,name --format=csv,noheader | grep -i 'P104-100' | cut -d, -f1); do
  nvidia-smi -i \$u -pm 1 >/dev/null 2>&1; [ "$POWER_W" != 0 ] && nvidia-smi -i \$u -pl $POWER_W >/dev/null 2>&1
  [ "$MEM_OFFSET" != 0 ] && [ -x /usr/local/sbin/p104-memoc-set.py ] && python3 -I /usr/local/sbin/p104-memoc-set.py $MEM_OFFSET \$u >/dev/null 2>&1
done; exit 0
E
chmod +x "$ROOT/fleet/power.sh"
sudo tee /etc/systemd/system/p104-fleet-power.service >/dev/null <<E
[Unit]
Description=P104-100 fleet power cap ($POWER_W W) and memory offset ($MEM_OFFSET)
After=multi-user.target
[Service]
Type=oneshot
ExecStart=$ROOT/fleet/power.sh
[Install]
WantedBy=multi-user.target
E
# router: nginx least-connections over the cards, one public port, long timeouts for long generations
if ! command -v nginx >/dev/null; then sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq nginx >/dev/null; fi
{ echo "upstream bonsai_fleet { least_conn;"; for entry in "${CARDS[@]}"; do idx=${entry%%,*}; echo "  server 127.0.0.1:$((BASE_PORT+idx)) max_fails=3 fail_timeout=30s;"; done; echo "}"
  cat <<E
server {
  listen $ROUTER_PORT;
  client_max_body_size 64m;
  location / {
    proxy_pass http://bonsai_fleet;
    proxy_http_version 1.1;
    proxy_buffering off;
    proxy_read_timeout 1800s; proxy_send_timeout 1800s;
    proxy_set_header Connection "";
  }
}
E
} | sudo tee /etc/nginx/sites-available/bonsai-fleet >/dev/null
sudo ln -sf /etc/nginx/sites-available/bonsai-fleet /etc/nginx/sites-enabled/bonsai-fleet; sudo rm -f /etc/nginx/sites-enabled/default
sudo nginx -t >/dev/null && sudo systemctl reload nginx
sudo systemctl daemon-reload; sudo systemctl enable --now p104-fleet-power.service >/dev/null
for entry in "${CARDS[@]}"; do idx=${entry%%,*}; sudo systemctl enable --now "bonsai@$idx.service" >/dev/null; done
echo "== waiting for $N servers to load the model (sequential loads over the PCIe links take a few minutes)"
for i in $(seq 1 600); do up=0; for entry in "${CARDS[@]}"; do idx=${entry%%,*}; curl -s -m 1 "http://127.0.0.1:$((BASE_PORT+idx))/health" 2>/dev/null | grep -q '"ok"' && up=$((up+1)); done; [ "$up" -eq "$N" ] && break; sleep 2; done
IP="$(hostname -I 2>/dev/null | awk '{print $1}')"
echo "== $up of $N cards serving. Router: http://${IP:-localhost}:$ROUTER_PORT/  (web UI and /v1 API; least-connections over all cards)"
echo "   per card: http://${IP:-localhost}:$BASE_PORT.. ; status: bash $ROOT/fleet/status.sh ; logs: journalctl -u bonsai@N"
cat > "$ROOT/fleet/status.sh" <<E
#!/usr/bin/env bash
nvidia-smi --query-gpu=index,name,temperature.gpu,power.draw,power.limit,clocks.mem,memory.used,utilization.gpu --format=csv
for f in $ROOT/fleet/card*.env; do . \$f; i=\${f##*card}; i=\${i%.env}; printf "card %s port %s: %s\n" "\$i" "\$PORT" "\$(curl -s -m 2 http://127.0.0.1:\$PORT/health || echo down)"; done
E
chmod +x "$ROOT/fleet/status.sh"
